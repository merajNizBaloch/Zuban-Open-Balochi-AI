import { writeFile } from "node:fs/promises";

const SOURCE =
  "https://raw.githubusercontent.com/Vuizur/Wiktionary-Dictionaries/master/Baluchi-English%20Wiktionary%20dictionary.tsv";

function decodeEntities(value) {
  return value
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&nbsp;/g, " ")
    .replace(/&#x27;/g, "'")
    .replace(/&#x2F;/g, "/");
}

function cleanHtml(value) {
  return decodeEntities(
    value
      .replace(/<[^>]+>/g, " ")
      .replace(/\s+/g, " ")
      .trim(),
  );
}

function isMostlyLatin(value) {
  const latin = (
    value.match(/[A-Za-zÁÉÍÓÚáéíóúČčŠšŽžÃÕãõÎîÂâÊêÛû]/g) ?? []
  ).length;
  const arabic = (value.match(/[\u0600-\u06FF]/g) ?? []).length;
  return latin > 0 && latin >= arabic;
}

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`Dictionary download failed: HTTP ${response.status}`);
}

const raw = await response.text();
const entries = [];

for (const line of raw.split(/\r?\n/)) {
  if (!line.trim() || !line.includes("\t")) continue;

  const [head, ...rest] = line.split("\t");
  const html = rest.join("\t");
  const headParts = head.split("|").map((item) => item.trim()).filter(Boolean);

  if (!headParts.length) continue;

  const word = headParts[0];
  const aliases = [];
  const latin = [];

  for (const part of headParts.slice(1)) {
    if (isMostlyLatin(part)) latin.push(part);
    else if (part !== word) aliases.push(part);
  }

  const parts = [...html.matchAll(/<i>(.*?)<\/i>/g)]
    .map((match) => cleanHtml(match[1]))
    .filter(Boolean);

  const meanings = [...html.matchAll(/<li>(.*?)<\/li>/g)]
    .map((match) => cleanHtml(match[1]))
    .filter(Boolean);

  if (!meanings.length) {
    const fallback = cleanHtml(html);
    if (fallback) meanings.push(fallback);
  }

  const uniqueMeanings = [...new Set(meanings)].slice(0, 20);
  if (!uniqueMeanings.length) continue;

  entries.push({
    word,
    ...(aliases.length ? { aliases: [...new Set(aliases)] } : {}),
    ...(latin.length ? { latin: [...new Set(latin)] } : {}),
    part: [...new Set(parts)].slice(0, 6).join(" / ") || "entry",
    meanings: uniqueMeanings,
  });
}

const seen = new Set();
const deduped = entries.filter((entry) => {
  const key =
    entry.word +
    "|" +
    (entry.latin ?? []).join("|") +
    "|" +
    entry.meanings.join("|");

  if (seen.has(key)) return false;
  seen.add(key);
  return true;
});

const generated = `/**
 * Generated from Vuizur/Wiktionary-Dictionaries:
 * "Baluchi-English Wiktionary dictionary.tsv"
 *
 * Upstream data is extracted from Wiktionary and dual-licensed under
 * CC BY-SA 3.0 and GFDL. This data license is separate from Zubán's
 * Apache-2.0 software license.
 *
 * Generated by: npm run update:dictionary
 */

export type DictionaryEntry = {
  word: string;
  aliases?: string[];
  latin?: string[];
  part: string;
  meanings: string[];
};

export const dictionarySource = {
  name: "Baluchi-English Wiktionary dictionary",
  url: "https://github.com/Vuizur/Wiktionary-Dictionaries/blob/master/Baluchi-English%20Wiktionary%20dictionary.tsv",
  license: "CC BY-SA 3.0 / GFDL",
  note: "Extracted from Wiktionary through Wiktextract. Entries can contain regional, spelling, or transcription variants.",
};

export const dictionaryEntries: DictionaryEntry[] = ${JSON.stringify(deduped, null, 2)};
`;

await writeFile("src/lib/dictionary.ts", generated, "utf8");
console.log(`Wrote ${deduped.length} Baluchi dictionary entries.`);
